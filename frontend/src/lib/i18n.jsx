export function normalizeLang(language) {
  if (!language) return DEFAULT_LANG
  if (DICT[language]) return language
  if (language.startsWith('en')) return 'en-US'
  if (language.startsWith('ja')) return 'ja-JP'
  if (language.startsWith('ko')) return 'ko-KR'
  if (language.startsWith('fil') || language.startsWith('tl')) return 'fil-PH'
  if (language.startsWith('zh')) return 'zh-CN'
  return DEFAULT_LANG
}

export function getLangGroup(language) {
  const lang = normalizeLang(language)
  if (lang === 'en-US') return 'en'
  if (lang === 'ja-JP') return 'ja'
  if (lang === 'ko-KR') return 'ko'
  if (lang === 'fil-PH') return 'fil'
  return 'zh'
}

export function t(language, key, fallback = '') {
  const lang = normalizeLang(language)
  return DICT[lang]?.[key] || DICT[DEFAULT_LANG]?.[key] || fallback || key
}

export function navLabel(language, id, fallbackZh) {
  return t(language, `nav.${id}`, fallbackZh)
}

export function typeLabel(language, type, full = false) {
  return t(language, full ? `type.${type}Full` : `type.${type}`, type)
}

const LanguageContext = createContext({
  language: DEFAULT_LANG,
  langGroup: 'zh',
  t: (key, fallback) => t(DEFAULT_LANG, key, fallback),
})

export function LanguageProvider({ language, children }) {
  const value = useMemo(() => {
    const lang = normalizeLang(language)
    return {
      language: lang,
      langGroup: getLangGroup(lang),
      t: (key, fallback) => t(lang, key, fallback),
    }
  }, [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useI18n() {
  return useContext(LanguageContext)
}

